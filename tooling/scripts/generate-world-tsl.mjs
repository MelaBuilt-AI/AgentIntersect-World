// Offline translation of the authored World formulas; never shipped to browsers.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { pathToFileURL, URL } from "node:url";
const root = new URL("../../", import.meta.url);
const require = createRequire(
  new URL("packages/renderer-r3f/package.json", root),
);
const addon = (file) =>
  import(
    pathToFileURL(require.resolve(`three/addons/transpiler/${file}.js`)).href
  );
const { default: Transpiler } = await addon("Transpiler");
const { default: GLSLDecoder } = await addon("GLSLDecoder");
const { default: TSLEncoder } = await addon("TSLEncoder");
const source = readFileSync(
  new URL("tooling/world-shaders.glsl", root),
  "utf8",
);
const transpiler = new Transpiler(new GLSLDecoder(), new TSLEncoder());
const ast = transpiler.decoder.parse(source);
transpiler.linker.process(ast);
// Inline texture-bearing functions: a GLSL sampler2D layout parameter is not a
// TSL TextureNode and therefore cannot expose sample(). Keep texture nodes bound.
for (const fn of ast.body)
  if (fn.params?.some((param) => param.type === "sampler2D")) fn.layout = false;
// r186's linker misses writes through vector swizzles. Materialize these
// authored mutable locals instead of aliasing an immutable WGSL parameter.
function preserveValueCopies(node) {
  if (!node?.isASTNode) return;
  if (node.isVariableDeclaration && node.value) node.needsToVar = true;
  for (const [key, value] of Object.entries(node)) {
    if (key === "parent" || key === "linker") continue;
    if (Array.isArray(value)) value.forEach(preserveValueCopies);
    else if (value?.isASTNode) preserveValueCopies(value);
  }
}
preserveValueCopies(ast);
const output = transpiler.encoder.emit(ast);
writeFileSync(
  new URL("packages/renderer-r3f/src/world-tsl.js", root),
  "// Generated by tooling/scripts/generate-world-tsl.mjs from tooling/world-shaders.glsl.\n" +
    output,
);
